GRANT EXECUTE ON FUNCTION public.receive_multi_product_transfer(TEXT, TEXT) TO service_role;

-- SECURITY NOTE:
-- This migration does not alter or replace existing single-product transfer
-- functions. The new RPCs are SECURITY DEFINER, but they are not intended to be
-- public or unauthenticated entry points. The actual application authenticates
-- with a custom Node/Express JWT (req.user.id, req.user.username, req.user.role,
-- req.user.branch), and the backend must resolve branch identity from that
-- verified context before invoking these RPCs.
--
-- The new RPCs are executable only by the service_role used by the backend.
--
-- The backend must also supply p_created_by and p_received_by from req.user,
-- never from a client-controlled auth payload.
--
-- HISTORY INTEGRATION NOTE (conceptual, not implemented in this migration):
-- The existing /api/transfers/history and Deliveries page currently aggregate
-- stock_transactions history. Those callers must eventually be updated to
-- understand transfer-header grouping instead of counting rows only.
--
-- Required backend response changes for the new multi-product transfer flow:
--  1. Keep legacy single-product transfer payloads unchanged for old records.
--  2. Emit one aggregate transfer group per tracking_code for new multi-product
--     transfers, with a single top-level transfer record and a nested products[]
--     array under it.
--  3. Each nested product item keeps the original product order and quantity,
--     without duplicating the same transfer via both TRANSFER_OUT and TRANSFER_IN.
--  4. Aggregation must group by transfer_headers.id or tracking_code and exclude
--     the duplicate count of matching TRANSFER_OUT/TRANSFER_IN rows from the same
--     transfer when building the UI totals.
--  5. Do not write any new delivery_transactions rows in this migration: the
--     existing transaction history is still the source of truth for legacy data,
--     and the new history grouping should be added in the backend contract rather
--     than by modifying the transaction schema here.
--
-- This migration intentionally does not add delivery_transactions writes because
-- there is no verified requirement for backward-compatible history and doing so
-- would duplicate the single-product transfer history model that the current UI
-- already consumes.

